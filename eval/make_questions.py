def keys_for(key: str, value: str) -> list[str]:
    if key.endswith(".channel") or key.endswith(".estop"):
        return [p.strip() for p in value.split(",")]  # «слот 2», «канал 4»
    if key.startswith("plc.err."):
        return [value.split()[0]]  # первое слово описания: «обрыв»
    return [value]


def build(items, traps, prefix: str, facts: dict) -> list[dict]:
    rows = []
    for n, (q, key) in enumerate(items, 1):
        f = facts[key]
        unit = f.get("unit", "")
        rows.append({"id": f"{prefix}{n:02d}", "kind": "answerable", "question": q,
                     "answer": f"{f['value']} {unit}".strip(), "answer_keys": keys_for(key, f["value"]),
                     "sources": f["docs"], "fact": key})
    for n, q in enumerate(traps, 1):
        rows.append({"id": f"{prefix}T{n:02d}", "kind": "trap", "question": q, "answer": None,
                     "answer_keys": [], "sources": [], "fact": None})
    return rows


def main() -> None:
    facts = json.loads(FACTS.read_text(encoding="utf-8"))["facts"]
    for name, rows in [("questions.jsonl", build(ANSWERABLE, TRAPS, "Q", facts)),
                       ("calibration.jsonl", build(CALIB_ANSWERABLE, CALIB_TRAPS, "C", facts))]:
        with open(Path(__file__).parent / name, "w", encoding="utf-8") as fh:
            for r in rows:
                fh.write(json.dumps(r, ensure_ascii=False) + "\n")
        print(f"{name}: {len(rows)} строк")


if __name__ == "__main__":
    main()
